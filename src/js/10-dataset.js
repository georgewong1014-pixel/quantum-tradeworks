/* ==========================================================================
   DATASET — synthetic
   --------------------------------------------------------------------------
   fin rows are [revenue, ebit, netIncome, opCashFlow, capex, equity, debt,
   cash, shares, dpsPerShare] for FY2021..FY2025.
   Currency units: billions of the reporting currency; `shares` in billions.
   Banks report `rev` as total operating income and `ebit` as pre-provision
   operating profit; operating cash flow is intentionally null (not meaningful
   for a deposit-taking balance sheet) so the app must handle missing data
   rather than impute it.
   ========================================================================== */
const YEARS = [2016, 2017, 2018, 2019, 2020, 2021, 2022, 2023, 2024, 2025];
const LYI = YEARS.length - 1;          /* index of the latest reported year */
const AUTHORED_YEARS = 5;              /* the rows written out below, FY2021–FY2025 */

/* Per-line annual growth bands used to reconstruct the earlier history.
   Order matches the fin tuple: rev, ebit, ni, ocf, capex, eq, debt, cash, sh, dps. */
const BACKCAST_BAND = [
  [1.02, 1.14], [1.00, 1.18], [1.00, 1.20], [1.02, 1.16], [1.00, 1.20],
  [1.02, 1.12], [0.98, 1.10], [0.95, 1.15], [0.995, 1.012], [1.00, 1.15],
];

/* The authored dataset carries five reported years. Ten are needed, so five
   earlier ones are reconstructed backwards from the earliest authored year
   using a deterministic per-company, per-line growth factor. The whole dataset
   is synthetic, so this adds no new class of fiction — and nulls and zeros are
   preserved, so a bank's absent cash-flow lines stay absent rather than being
   invented. */
function backcast(c) {
  const rnd = seeded(c.id + 'hist');
  const out = [];
  let cur = c.fin[0];
  for (let k = 0; k < YEARS.length - AUTHORED_YEARS; k++) {
    const prior = cur.map((v, j) => {
      if (v == null) return null;
      if (v === 0) return 0;
      const [lo, hi] = BACKCAST_BAND[j];
      return +(v / (lo + rnd() * (hi - lo))).toFixed(4);
    });
    out.unshift(prior);
    cur = prior;
  }
  return out;
}

